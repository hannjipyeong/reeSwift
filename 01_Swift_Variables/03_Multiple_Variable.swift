// kita juga bsia mendeklarasikan beberapa variable sekaligus dalam satu baris
// tapi keyword nya harus sama, contoh:
var a = 1, b = 2, c = 3
let d = 4, e = 5, f = 6

print(a, b, c, d, e, f, separator: ", ")

// kita juga bisa mendeklarasikan nya menggunakan type annotation, contoh:
var firstName: String = "Raihan", lastName: String = "Ganteng"
print(firstName, lastName, separator: " sangat ")